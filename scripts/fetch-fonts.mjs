/**
 * Self-hosts the four brand fonts so builds never depend on the Google Fonts
 * network at compile time.
 *
 *   node scripts/fetch-fonts.mjs
 */
import fs from "node:fs/promises";
import path from "node:path";

const UA =
  "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/122.0 Safari/537.36";

const FAMILIES = [
  "Cormorant+Garamond:ital,wght@0,300;0,400;0,500;0,600;0,700;1,400;1,500",
  "Inter:wght@300;400;500;600",
  "Noto+Sans+Devanagari:wght@400;500;600",
  "Great+Vibes",
];

const outDir = path.join(process.cwd(), "public", "fonts");
const cssPath = path.join(process.cwd(), "src", "app", "fonts.css");

await fs.mkdir(outDir, { recursive: true });

const rules = [];

for (const family of FAMILIES) {
  const url = `https://fonts.googleapis.com/css2?family=${family}&display=swap`;
  const res = await fetch(url, { headers: { "User-Agent": UA } });
  if (!res.ok) throw new Error(`Failed to fetch CSS for ${family}: ${res.status}`);
  const text = await res.text();

  const blocks = text.split("@font-face").slice(1);
  for (const [i, block] of blocks.entries()) {
    const pick = (re) => block.match(re)?.[1]?.trim();
    const name = pick(/font-family:\s*'([^']+)'/);
    const style = pick(/font-style:\s*(\w+)/) ?? "normal";
    const weight = pick(/font-weight:\s*(\d+)/) ?? "400";
    const src = pick(/url\((https:[^)]+)\)/);
    const range = pick(/unicode-range:\s*([^;]+);/);
    if (!name || !src) continue;

    const filename = `${name.replace(/\s+/g, "-").toLowerCase()}-${weight}-${style}-${i}.woff2`;
    const buffer = Buffer.from(await (await fetch(src)).arrayBuffer());
    await fs.writeFile(path.join(outDir, filename), buffer);

    rules.push(
      `@font-face { font-family: "${name}"; font-style: ${style}; font-weight: ${weight}; font-display: swap; src: url("/fonts/${filename}") format("woff2");${
        range ? ` unicode-range: ${range};` : ""
      } }`,
    );
  }
}

const header = `/* Generated by scripts/fetch-fonts.mjs — self-hosted brand fonts. Do not edit by hand. */\n`;
await fs.writeFile(cssPath, header + rules.join("\n") + "\n", "utf8");

console.log(`✓ ${rules.length} @font-face rules, files in public/fonts`);
